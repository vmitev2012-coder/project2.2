def age_for(title, genre):
    for group, titles in AGE_OVERRIDE.items():
        if title in titles:
            return group
    return AGE_DEFAULT.get(genre, "Adults")


BOOKS = []
for genre, items in CATALOG.items():
    for title, author, year in items:
        BOOKS.append(
            {"title": title, "author": author, "genre": genre, "year": year,
             "age": age_for(title, genre), "release": None}
        )
for title, author, genre, release, age in UPCOMING:
    BOOKS.append(
        {"title": title, "author": author, "genre": genre, "year": int(release[:4]),
         "age": age, "release": release}
    )
for i, book in enumerate(BOOKS):
    book["copies"] = 1 + (i * 7) % 4
    book["popularity"] = POPULARITY.get(book["title"], 0)
